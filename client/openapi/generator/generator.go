// Package generator writes Go types and a thin typed client for meshObject kinds of the meshStack
// API docs. A repository builds its Config in a small main package of its own, so that the config
// can carry functions such as the TypeMapper, and runs it with Main from a go:generate line.
package generator

import (
	"cmp"
	"fmt"
	"path"
	"slices"
	"strings"

	"github.com/meshcloud/meshstack-cli/client/openapi"
)

type Config struct {
	// Module is the import path of the directory the packages are written below, such as
	// github.com/meshcloud/meshstack-cli/client.
	Module string
	// Shared is the path below Module of the package for the schemas that several packages reach.
	// It holds a hand-written Links type, which every _links field takes.
	Shared   string
	Packages []Package
	// MapType decides the Go type of a schema before the generator does. It must map every oneOf
	// without a discriminator.
	MapType TypeMapper
}

// Package selects the operations of one meshObject kind in one API version, or of operation IDs.
type Package struct {
	Kind string
	// Actions are those of openapi.Operation, such as list, show or trigger-run.
	Actions    []string
	ApiVersion string
	// OperationIds select operations outside the path of a kind.
	OperationIds []string
	// Path below Config.Module defaults to the kind in lower case and the version's number, as
	// meshworkspace/v2.
	Path string
	// Name of the Go package defaults to the kind in lower case.
	Name string
}

type GoType struct {
	// Expr is the type as a file writes it, qualified by the last element of Import.
	Expr   string
	Import string
	// Container is a type whose zero value already says "absent", such as a slice, a map or an
	// any. A field never points to it.
	Container bool
}

// Location names where a schema occurs: the component, and the dotted path of the property in it.
type Location struct {
	Schema   string
	Property string
}

func (l Location) String() string {
	return strings.Trim(l.Schema+"."+l.Property, ".")
}

func (l Location) child(property string) Location {
	return Location{l.Schema, strings.Trim(l.Property+"."+property, ".")}
}

type TypeMapper func(at Location, schema *openapi.Schema) (GoType, bool)

const (
	header        = "// Code generated by github.com/meshcloud/meshstack-cli/client/openapi/generator. DO NOT EDIT.\n\n"
	runtimeImport = "github.com/meshcloud/meshstack-cli/client/internal"
	enumImport    = "github.com/meshcloud/meshstack-cli/client/types/enum"
	fileName      = "generated.go"
)

// Generate returns the content of each generated file by its path below Config.Module.
func Generate(spec openapi.Spec, cfg Config) (map[string][]byte, error) {
	g := newGenerator(spec, cfg)
	for _, p := range cfg.Packages {
		if err := g.addPackage(p); err != nil {
			return nil, err
		}
	}
	if err := g.place(); err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	for _, p := range append(slices.Clone(g.packages), g.shared) {
		if len(p.types) == 0 && len(p.operations) == 0 {
			continue
		}
		source, err := g.render(p)
		if err != nil {
			return nil, fmt.Errorf("package %s: %w", p.Path, err)
		}
		files[path.Join(p.Path, fileName)] = source
	}
	return files, nil
}

func (p Package) defaults() (Package, error) {
	if p.Kind == "" && (p.Path == "" || p.Name == "") {
		return p, fmt.Errorf("a package of operation IDs %v needs a Path and a Name", p.OperationIds)
	}
	if p.Kind != "" {
		version, err := openapi.ParseApiVersion(p.ApiVersion)
		if err != nil {
			return p, fmt.Errorf("package of %s: %w", p.Kind, err)
		}
		number, _, _ := strings.Cut(strings.TrimPrefix(version.String(), "v"), "-")
		p.Path = cmp.Or(p.Path, strings.ToLower(p.Kind)+"/v"+number)
		p.Name = cmp.Or(p.Name, strings.ToLower(p.Kind))
	}
	return p, nil
}
